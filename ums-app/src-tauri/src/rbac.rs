// Purpose: Role-to-capability mapping per DEC-055, DEC-057, and Stage 06 calendar additions. Uses read:X / write:X.

pub fn capabilities_for_role(role: &str) -> Vec<String> {
    let caps: &[&str] = match role {
        "super_admin" => &[
            "read:all",
            "write:all",
            "admin:profile",
            "admin:finance",
            "write:accounting",
            "write:executive",
            "write:finance",
            "write:tenders",
            "write:management",
            "write:hr",
            "read:calendar",
            "write:calendar",
        ],
        "devops_admin" => &[
            "read:all",
            "write:all",
            "admin:profile",
            "admin:finance",
            "write:accounting",
            "write:executive",
            "write:finance",
            "write:tenders",
            "write:management",
            "write:hr",
            "read:devops",
            "write:devops",
            "read:calendar",
            "write:calendar",
        ],
        "finance_manager" => &[
            "read:all",
            "write:accounting",
            "write:finance",
            "write:management",
            "write:executive",
            "admin:profile",
            "admin:finance",
            "read:calendar",
            "write:calendar",
        ],
        "accountant" => &[
            "read:all",
            "write:accounting",
            "write:finance",
            "admin:finance",
            "read:profile",
            "read:calendar",
        ],
        "pa" => &[
            "read:all",
            "write:executive",
            "write:finance",
            "write:tenders",
            "write:management",
            "read:profile",
            "read:calendar",
            "write:calendar",
        ],
        "pm" => &[
            "read:all",
            "write:management",
            "read:tenders",
            "read:finance",
            "admin:profile",
            "admin:finance",
            "read:profile",
            "read:calendar",
            "write:calendar",
        ],
        "technical_manager" => &[
            "read:all",
            "write:management",
            "write:tenders",
            "read:finance",
            "read:profile",
            "read:calendar",
        ],
        "hr" => &[
            "read:all",
            "write:hr",
            "read:profile",
            "read:calendar",
            "write:calendar",
        ],
        _ => &["read:all", "read:calendar"],
    };
    caps.iter().map(|s| s.to_string()).collect()
}
